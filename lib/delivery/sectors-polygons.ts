export function getSectorByCoordinates(lat: number, lng: number): string | null {
  for (const [sectorId, polygon] of Object.entries(SECTOR_POLYGONS)) {
    if (isPointInPolygon(lat, lng, polygon)) {
      return sectorId
    }
  }
  return null
}

function isPointInPolygon(lat: number, lng: number, polygon: [number, number][]) {
  let inside = false

  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][0]
    const yi = polygon[i][1]
    const xj = polygon[j][0]
    const yj = polygon[j][1]

    const intersect = ((yi > lat) !== (yj > lat)) &&
      (lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi)

    if (intersect) {
      inside = !inside
    }
  }

  return inside
}
